"""Original synthetic stone, thornwood and fungal boss effects; no samples."""
from pathlib import Path
import numpy as np
import wave, json
root=Path(__file__).resolve().parents[1]/'Assets/Audio/SFX/CrimsonBoss'
root.mkdir(parents=True,exist_ok=True)
sr=44100
rng=np.random.default_rng(606)
recipes={
 'BossSlamWarn':(.8,110,47,'warning'), 'BossLungeWarn':(.65,220,90,'wood'),
 'BossSporeWarn':(.85,270,530,'fungus'), 'BossSlam':(.7,98,31,'stone'),
 'BossShockwave':(.85,74,28,'stone'), 'BossLunge':(.5,280,52,'wood'),
 'BossVolley':(.55,490,130,'fungus'), 'BossHit':(.23,150,45,'stone'),
 'BossPhase':(1.25,65,155,'roar'), 'BossDeath':(1.1,95,22,'roar'),
 'BossThornWarn':(.9,160,440,'warning'), 'BossThorns':(.65,370,38,'wood')}
reports=[]
for name,(seconds,start,end,kind) in recipes.items():
 t=np.arange(int(sr*seconds))/sr
 frequency=start*(end/start)**(t/seconds)
 phase=2*np.pi*np.cumsum(frequency)/sr
 noise=rng.normal(0,1,len(t));low=np.convolve(noise,np.ones(24)/24,'same')
 x=np.sin(phase)*.45+np.sin(phase*1.49)*.17+np.sin(phase*2.07)*.10
 if kind=='stone':x+=low*1.8+noise*np.exp(-t*34)*.16
 elif kind=='wood':x+=np.diff(noise,prepend=0)*.12*(.6+.4*np.sin(t*55))
 elif kind=='fungus':x=np.sin(phase+2*np.sin(phase*1.5))*.43+low*.35
 elif kind=='roar':x=np.tanh(x*2.5)*.6+low*.8
 else:x*=np.linspace(.12,1,len(t));x+=low*.18
 env=np.minimum(1,t/.012)*np.minimum(1,(seconds-t)/.06)
 if kind!='warning':env*=np.exp(-t*(3 if kind!='roar' else 1.8))
 x*=env;x-=x.mean();x*=.65/max(np.max(np.abs(x)),1e-6)
 stereo=np.stack([x,x*.97],axis=1)
 with wave.open(str(root/(name+'.wav')),'wb') as w:
  w.setnchannels(2);w.setsampwidth(2);w.setframerate(sr);w.writeframes(np.round(stereo*32767).astype('<i2').tobytes())
 reports.append({'sound':name,'seconds':seconds,'peak':float(np.max(np.abs(stereo)))})
(root/'README.md').write_text('Original synthesized boss sound effects. Stone impacts, thornwood tearing, fungal pulses and phase/death roars. No third-party samples. Generated by Tools/ComposeCrimsonBossSfx.py. Scene-specific CrimsonBossCatalog preserves other scene sound assignments.\n')
(root/'Measurements.json').write_text(json.dumps(reports,indent=2)+'\n')
print('Generated',len(reports),'original boss effects; all peaks <= 0.65.')
